# Import libraries
import pandas as pd
import numpy as np
import matplotlib.pyplot as plt

from pyod.models.auto_encoder import AutoEncoder
from sklearn.model_selection import train_test_split
from sklearn.preprocessing import StandardScaler
from sklearn.metrics import classification_report, confusion_matrix, roc_auc_score

# Load dataset
data = pd.read_csv("creditcard.csv")

print("Dataset Shape:", data.shape)
print(data.head())
print("\nClass Distribution:")
print(data["Class"].value_counts())

# Separate features and target
X = data.drop("Class", axis=1)
y = data["Class"]

# Split dataset into training and testing sets
X_train, X_test, y_train, y_test = train_test_split(
    X,
    y,
    test_size=0.30,
    random_state=42,
    stratify=y
)

# Standardize the features
scaler = StandardScaler()

X_train = scaler.fit_transform(X_train)
X_test = scaler.transform(X_test)

# Create AutoEncoder model
model = AutoEncoder(
    hidden_neuron_list=[64, 32, 32, 64],
    epoch_num=30,
    batch_size=256,
    contamination=0.0017,
    preprocessing=False,
    verbose=1,
    random_state=42
)

# Train the model using training features only
print("\nTraining AutoEncoder...")
model.fit(X_train)

# Predict anomalies on test data
predictions = model.predict(X_test)

# Calculate anomaly scores
scores = model.decision_function(X_test)

# Evaluate the model
print("\nClassification Report:")
print(classification_report(
    y_test,
    predictions,
    target_names=["Genuine", "Fraud"],
    zero_division=0
))

# Confusion matrix
cm = confusion_matrix(y_test, predictions)

print("\nConfusion Matrix:")
print(cm)

# ROC-AUC score
roc_auc = roc_auc_score(y_test, scores)

print("\nROC-AUC Score:", roc_auc)

# Visualize confusion matrix
plt.figure(figsize=(6, 5))

plt.imshow(cm, interpolation="nearest", cmap="Blues")
plt.title("Fraud Detection Confusion Matrix")
plt.colorbar()

plt.xticks([0, 1], ["Genuine", "Fraud"])
plt.yticks([0, 1], ["Genuine", "Fraud"])

plt.xlabel("Predicted Label")
plt.ylabel("Actual Label")

for i in range(2):
    for j in range(2):
        plt.text(j, i, cm[i, j], ha="center", va="center")

plt.tight_layout()
plt.show()

# Visualize anomaly scores
plt.figure(figsize=(8, 5))

plt.hist(scores, bins=50)
plt.title("AutoEncoder Anomaly Scores")
plt.xlabel("Anomaly Score")
plt.ylabel("Frequency")

plt.tight_layout()
plt.show()

# Save predictions
results = pd.DataFrame({
    "Actual_Class": y_test.values,
    "Predicted_Class": predictions,
    "Anomaly_Score": scores
})

results.to_csv("fraud_detection_results.csv", index=False)

print("\nResults saved to fraud_detection_results.csv")
print("\nExperiment completed successfully.")

